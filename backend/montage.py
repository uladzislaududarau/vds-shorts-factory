class MusicRequest(StrictModel):
    style: Literal['kids', 'action', 'epic', 'fun', 'chill', 'tension', 'romantic', 'sport', 'hiphop', 'inspire', 'comedy', 'horror', 'custom']
    tempo: Literal['auto', 'slow', 'medium', 'fast'] = 'auto'
