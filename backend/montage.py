def music_prompt(request: MusicRequest, duration):
    parts = [MUSIC_PREFIX, MUSIC_STYLES[request.style][1], TEMPOS[request.tempo][1]]
    if request.notes.strip():
        parts.append('Editor\'s wishes (follow them): ' + ' '.join(request.notes.split()))
    parts.append(f'Background score for a {round(duration)}-second short video edit: consistent energy that sits under the clips\' own sound, '
                 'starts right away and ends naturally at the very end.')
    return ' '.join(p for p in parts if p)[:2000]

