def caption_preview(style: str, format: str = '9:16', crop: bool = False):
    if format not in SIZES or len(style) > 2000:
        raise ValueError('Invalid preview request')
    parsed = CaptionStyle.model_validate_json(style)
    width, height = SIZES[format]
    key = preview_key(parsed, width, height, crop)
    path = PREVIEW_DIR / f'{key}.png'
    if not path.exists():
        data = preview_png(parsed, width, height, crop=crop)
        if not crop:
            # Full-frame overlay for the player: rendered at output size, served at half size.
            import io
            from PIL import Image
            image = Image.open(io.BytesIO(data)).resize((width // 2, height // 2), Image.Resampling.LANCZOS)
            buffer = io.BytesIO()
            image.save(buffer, format='PNG', optimize=True)
            data = buffer.getvalue()
        pending = path.with_suffix('.tmp')
        pending.write_bytes(data)
        pending.replace(path)
    return Response(path.read_bytes(), media_type='image/png', headers={'Cache-Control': 'max-age=86400'})
