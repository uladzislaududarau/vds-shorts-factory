def probe_audio(path: Path):
    demuxer = AUDIO_EXT.get(path.suffix.lower())
    if not demuxer:
        raise ValueError('Поддерживаются аудиофайлы MP3, WAV, M4A, AAC, OGG, FLAC')
    raw = json.loads(run([FFPROBE, '-v', 'error', '-protocol_whitelist', 'file,pipe', '-f', demuxer,
                          '-show_format', '-show_streams', '-of', 'json', path], timeout=60))
    if not any(s['codec_type'] == 'audio' for s in raw.get('streams', [])):
        raise ValueError('Файл не содержит звуковую дорожку')
    duration = float(raw.get('format', {}).get('duration', 0) or 0)
    if not 0 < duration < 3 * 3600:
        raise ValueError('Длительность аудио не определена или больше 3 часов')
    return {'duration': duration, 'width': 0, 'height': 0, 'has_audio': 1}

def register_media(path: Path, name: str):
    """Validate an uploaded file by its content, deduplicate by SHA-256 and move it into the montage library."""
    ext = path.suffix.lower()
    kind = 'video' if ext in VIDEO_EXT else 'audio' if ext in AUDIO_EXT else None
    if not kind:
        raise ValueError('Поддерживаются видео MP4, MOV, MKV, WebM и аудио MP3, WAV, M4A, AAC, OGG, FLAC')
    digest = hashlib.sha256()
    with path.open('rb') as handle:
        for chunk in iter(lambda: handle.read(1024 ** 2), b''):
            digest.update(chunk)
    sha = digest.hexdigest()
    old = db.one('SELECT * FROM montage_media WHERE sha256=?', (sha,))
    if old:
        return media_json(old)
    info = probe(path) if kind == 'video' else probe_audio(path)
    mid = db.uid()
    dest = MEDIA_DIR / f'{mid}{ext}'
    thumb = MEDIA_DIR / f'{mid}.jpg' if kind == 'video' else None
    try:
        path.replace(dest)
        if thumb:
            thumbnail(dest, thumb, info['duration'])
        db.execute('INSERT INTO montage_media VALUES(?,?,?,?,?,?,?,?,?,?,?)',
                   (mid, kind, Path(name).name[:200], str(dest.relative_to(DATA)), sha, info['duration'], info['width'],
                    info['height'], info['has_audio'], str(thumb.relative_to(DATA)) if thumb else None, time.time()))
    except BaseException:
        dest.unlink(missing_ok=True)
        if thumb:
            thumb.unlink(missing_ok=True)
        raise
    return media_json(db.one('SELECT * FROM montage_media WHERE id=?', (mid,)))

def media_json(row):
    return {'id': row['id'], 'kind': row['kind'], 'name': row['name'], 'duration': row['duration'],
            'width': row['width'], 'height': row['height'], 'has_audio': bool(row['has_audio']),
            'media_url': f'/api/montage/media/{row["id"]}/file',
            'thumbnail_url': f'/api/montage/media/{row["id"]}/thumbnail' if row['thumbnail'] else None}

_PROBES = {}
def _probe_cached(path):
    stat = path.stat()
    key = (str(path), stat.st_size, stat.st_mtime_ns)
    if key not in _PROBES:
        _PROBES[key] = probe(path)
    return _PROBES[key]

def resolve(kind, media_id):
    """Where a clip's pixels come from. Never trusts a path from the client."""
    if kind == 'upload':
        row = db.one("SELECT * FROM montage_media WHERE id=? AND kind='video'", (media_id,))
        if not row:
            raise ValueError('Загруженный клип не найден')
        info = media_json(row)
        return {**info, 'path': safe_path(row['path']), 'title': row['name']}
    if kind == 'source':
        row = db.one('SELECT * FROM sources WHERE id=?', (media_id,))
        if not row or not row['path']:
            raise ValueError('Исходник клипа из библиотеки недоступен на диске')
        return {'id': row['id'], 'path': safe_path(row['path']), 'title': row['name'], 'duration': row['duration'],
                'width': row['width'], 'height': row['height'], 'has_audio': bool(row['has_audio']),
                'media_url': f'/api/sources/{row["id"]}/media',
                'thumbnail_url': f'/api/sources/{row["id"]}/thumbnail' if row['thumbnail'] else None}
    row = db.one('SELECT c.*,s.thumbnail FROM clips c JOIN sources s ON s.id=c.source_id WHERE c.id=?', (media_id,))
    if not row or not row['render_path']:
        raise ValueError('Готовый MP4 клипа из библиотеки не найден. Создайте его через Generate Reel или добавьте фрагмент.')
    path = safe_path(row['render_path'])
    if not path.exists():
        raise ValueError('Файл готового клипа удалён с диска')
    info = _probe_cached(path)
    return {'id': row['id'], 'path': path, 'title': row['title'], 'duration': info['duration'], 'width': info['width'],
            'height': info['height'], 'has_audio': bool(info['has_audio']), 'media_url': f'/api/clips/{row["id"]}/media',
            'thumbnail_url': f'/api/sources/{row["source_id"]}/thumbnail' if row['thumbnail'] else None}

def audio_media(media_id):
    row = db.one('SELECT * FROM montage_media WHERE id=?', (media_id,))
    if not row or not row['has_audio']:
        raise ValueError('Аудиофайл не найден')
    return row

def validate_media(plan: MontagePlan):
    for clip in plan.clips:
        info = resolve(clip.media_kind, clip.media_id)
        if clip.end > info['duration'] + .05:
            raise ValueError(f'Обрезка клипа «{info["title"]}» выходит за его длительность')
    for item in plan.audio:
        row = audio_media(item.media_id)
        if item.offset >= row['duration']:
            raise ValueError(f'Начало внутри файла «{row["name"]}» больше его длительности')

# ---------------------------------------------------------------- words

def whisper_model():
    return db.settings()['whisper_model']

def words_key(clip: ClipItem, language, model):
    """Uploads/renders are transcribed whole; library fragments reuse the source transcript or a range."""
    if clip.media_kind == 'source':
        if db.one('SELECT 1 FROM transcripts WHERE source_id=?', (clip.media_id,)):
            return None
        material = ['source', clip.media_id, round(clip.start, 2), round(clip.end, 2), model, language]
    elif clip.media_kind == 'render':
        path = resolve('render', clip.media_id)['path']
        stat = path.stat()
        material = ['render', clip.media_id, stat.st_size, stat.st_mtime_ns, model, language]
    else:
        material = ['upload', clip.media_id, model, language]
    return hashlib.sha256(db.dump(material).encode()).hexdigest()

def media_words(clip: ClipItem, language, model):
    """Recognised words in the clip's own media time, or None when recognition has not run yet."""
    if clip.media_kind == 'source':
        row = db.one('SELECT data FROM transcripts WHERE source_id=?', (clip.media_id,))
        if row:
            from .analysis import transcript_words
            return transcript_words(json.loads(row['data']))
    if not resolve(clip.media_kind, clip.media_id)['has_audio']:
        return []
    path = WORDS_DIR / f'{words_key(clip, language, model)}.json'
    return json.loads(path.read_text()) if path.exists() else None

def clip_words(plan: MontagePlan, clip: ClipItem, model):
    """Words inside the trimmed range, still in media time. Manual edits win."""
    if clip.id in plan.caption_edits:
        return [w.model_dump() for w in plan.caption_edits[clip.id]]
    words = media_words(clip, plan.language, model)
    if words is None:
        return None
    return [w for w in words if w['start'] >= clip.start - .025 and w['end'] <= clip.end + .025]

def missing_words(plan: MontagePlan, model):
    if not plan.subtitles.enabled:
        return []
    return [c for c in plan.clips if c.captions and clip_words(plan, c, model) is None]

def transcribe_clip(clip: ClipItem, language, model, job_id, ffmpeg_sem, whisper_sem):
    key = words_key(clip, language, model)
    target = WORDS_DIR / f'{key}.json'
    if target.exists():
        return
    info = resolve(clip.media_kind, clip.media_id)
    folder = DATA / 'temp' / f'{job_id}-words'
    folder.mkdir(parents=True, exist_ok=True)
    try:
        wav, raw = folder / f'{clip.id}.wav', folder / f'{clip.id}.json'
        offset = clip.start if clip.media_kind == 'source' else 0
        args = [FFMPEG, '-hide_banner', '-loglevel', 'error', '-y']
        if clip.media_kind == 'source':
            args += ['-ss', f'{clip.start:.3f}', '-t', f'{clip.end - clip.start:.3f}']
        args += ['-i', info['path'], '-vn', '-ac', '1', '-ar', '16000', '-c:a', 'pcm_s16le', wav]
        with ffmpeg_sem:
            run(args, job_id, timeout=600)
        with whisper_sem:
            run([sys.executable, '-m', 'workers.transcribe', wav, raw, model, language], job_id, timeout=3600)
        from .analysis import transcript_words
        words = [{**w, 'start': w['start'] + offset, 'end': w['end'] + offset}
                 for w in transcript_words(json.loads(raw.read_text()))]
        pending = target.with_suffix('.tmp')
        pending.write_text(db.dump(words), encoding='utf-8')
        pending.replace(target)
    finally:
        shutil.rmtree(folder, ignore_errors=True)

def transcribe_all(plan: MontagePlan, job_id, ffmpeg_sem, whisper_sem, base=0, span=100):
    model = whisper_model()
    todo = missing_words(plan, model)
    for n, clip in enumerate(todo):
        check_job(job_id)
        db.job_update(job_id, stage=f'Распознаю речь · клип {n + 1} из {len(todo)}', progress=base + span * n / max(1, len(todo)))
        transcribe_clip(clip, plan.language, model, job_id, ffmpeg_sem, whisper_sem)

def timeline_words(plan: MontagePlan, model):
    """All caption words on the output timeline."""
    result, offset = [], 0.0
    for index, clip in enumerate(plan.clips):
        length = clip.end - clip.start
        if clip.captions:
            for w in clip_words(plan, clip, model) or []:
                start = max(offset, w['start'] - clip.start + offset)
                end = min(offset + length, w['end'] - clip.start + offset)
                if end > start:
                    result.append({'word': w['word'], 'start': start, 'end': end, 'clip': index})
        offset += length
    return result

# ---------------------------------------------------------------- render

def video_chain(index, length, fit, width, height, fps):
    src, out = f'{index}:v', f'v{index}'
    # Exact segment length: a short last frame is cloned so audio never drifts across cuts.
    head = (f'[{src}]setpts=PTS-STARTPTS,fps={fps},tpad=stop_mode=clone:stop_duration=1,'
            f'trim=duration={length:.3f},setpts=PTS-STARTPTS')
    if fit == 'fill':
        return (f'{head},scale={width}:{height}:force_original_aspect_ratio=increase,'
                f'crop={width}:{height},setsar=1,format=yuv420p[{out}]')
    if fit == 'fit':
        return (f'{head},scale={width}:{height}:force_original_aspect_ratio=decrease,'
                f'pad={width}:{height}:(ow-iw)/2:(oh-ih)/2:black,setsar=1,format=yuv420p[{out}]')
    return (f'{head},split=2[bg{index}][fg{index}];'
            f'[bg{index}]scale={width}:{height}:force_original_aspect_ratio=increase,crop={width}:{height},boxblur=20:2[blur{index}];'
            f'[fg{index}]scale={width}:{height}:force_original_aspect_ratio=decrease[fit{index}];'
            f'[blur{index}][fit{index}]overlay=(W-w)/2:(H-h)/2,setsar=1,format=yuv420p[{out}]')

def build_command(plan: MontagePlan, words, folder, job_id):
    width, height = SIZES[plan.format]
    duration = plan.duration()
    args = [FFMPEG, '-hide_banner', '-loglevel', 'error', '-y']
    filters = []
    n = len(plan.clips)
    for index, clip in enumerate(plan.clips):
        info = resolve(clip.media_kind, clip.media_id)
        length = clip.end - clip.start
        args += ['-ss', f'{clip.start:.3f}', '-t', f'{length:.3f}', '-i', info['path']]
        filters.append(video_chain(index, length, plan.fit, width, height, plan.fps))
        if info['has_audio'] and not clip.muted and clip.volume > 0:
            filters.append(f'[{index}:a]asetpts=PTS-STARTPTS,aresample=48000,aformat=channel_layouts=stereo,'
                           f'volume={clip.volume},apad,atrim=duration={length:.3f}[a{index}]')
        else:
            filters.append(f'anullsrc=r=48000:cl=stereo,atrim=duration={length:.3f}[a{index}]')
    filters.append(''.join(f'[v{i}][a{i}]' for i in range(n)) + f'concat=n={n}:v=1:a=1[video][clips]')
    mix = ['[clips]']
    next_input = n
    for k, item in enumerate(plan.audio):
        if item.at >= duration:
            continue
        row = audio_media(item.media_id)
        length = min(item.duration, row['duration'] - item.offset, duration - item.at)
        if length <= .05:
            continue
        args += ['-ss', f'{item.offset:.3f}', '-t', f'{length:.3f}', '-i', safe_path(row['path'])]
        chain = f'[{next_input}:a]asetpts=PTS-STARTPTS,aresample=48000,aformat=channel_layouts=stereo,volume={item.volume}'
        if item.fade_in:
            chain += f',afade=t=in:d={min(item.fade_in, length):.3f}'
        if item.fade_out:
            fade = min(item.fade_out, length)
            chain += f',afade=t=out:st={length - fade:.3f}:d={fade:.3f}'
        chain += f',adelay={round(item.at * 1000)}:all=1[x{k}]'
        filters.append(chain)
        mix.append(f'[x{k}]')
        next_input += 1
    tail = 'loudnorm=I=-14:TP=-1.5:LRA=11,aresample=48000,' if plan.normalize else ''
    if len(mix) > 1:
        filters.append(''.join(mix) + f'amix=inputs={len(mix)}:duration=first:dropout_transition=0:normalize=0,'
                       f'{tail}alimiter=limit=.97,atrim=duration={duration:.3f}[audio]')
    else:
        filters.append(f'[clips]{tail}alimiter=limit=.97,atrim=duration={duration:.3f}[audio]')
    if plan.subtitles.enabled and words:
        concat = render_concat(words, plan.subtitles, width, height, duration, folder / 'captions', job_id)
        args += ['-f', 'concat', '-safe', '0', '-i', concat]
        filters.append(f'[{next_input}:v]fps={plan.fps},format=rgba[subs]')
        filters.append('[video][subs]overlay=0:0:eof_action=pass:format=auto,format=yuv420p[out]')
    else:
        filters.append('[video]format=yuv420p[out]')
    args += ['-filter_complex', ';\n'.join(filters), '-filter_complex_threads', '2', '-map', '[out]', '-map', '[audio]',
             '-c:a', 'aac', '-b:a', '192k', '-t', f'{duration:.3f}', '-r', str(plan.fps), '-movflags', '+faststart', '-pix_fmt', 'yuv420p']
    return args

def render_project(job, ffmpeg_sem, whisper_sem):
    from .metadata import output_options, audit
    from .render import quality_check
    jid = job['id']
    payload = json.loads(job['payload'])
    plan = MontagePlan.model_validate(payload['plan'])
    if not plan.clips:
        raise ValueError('Добавьте хотя бы один клип')
    validate_media(plan)
    duration = plan.duration()
    width, height = SIZES[plan.format]
    check_space(int(duration * 4_000_000), db.settings()['min_free_mb'])
    transcribe_all(plan, jid, ffmpeg_sem, whisper_sem, base=2, span=28)
    model = whisper_model()
    words = timeline_words(plan, model) if plan.subtitles.enabled else []
    folder = DATA / 'temp' / jid
    folder.mkdir(parents=True, exist_ok=True)
    output = DATA / 'renders' / f'montage-{payload["project_id"]}-r{payload["revision"]}-{jid[:8]}.mp4'
    try:
        check_job(jid)
        db.job_update(jid, stage='Подготовка кадров и субтитров', progress=32)
        args = build_command(plan, words, folder, jid)
        db.job_update(jid, stage='Rendering', progress=40)
        db.log(jid, f'Montage {len(plan.clips)} clips, {len(plan.audio)} audio items, {duration:.2f}s, {width}×{height}')
        quality = ['-c:v', 'libx264', '-preset', 'veryfast', '-crf', str(plan.quality), '-threads', '2']
        with ffmpeg_sem:
            check_job(jid)
            try:
                run(args + ['-c:v', 'h264_videotoolbox', '-b:v', '10M' if plan.format == '16:9' else '8M', '-allow_sw', '0',
                            *output_options(), output], jid)
                encoder = 'h264_videotoolbox'
            except RuntimeError:
                db.log(jid, 'VideoToolbox unavailable; using libx264')
                run(args + quality + [*output_options(), output], jid)
                encoder = 'libx264'
        db.job_update(jid, stage='Quality check', progress=88)
        qc = quality_check(output, duration, width, height, plan.fps, True, jid)
        qc.update(audit(probe(output)['raw']))
        if not qc['metadata_clean']:
            raise ValueError('Выходной MP4 содержит непредусмотренные метаданные')
        qc.update({'encoder': encoder, 'word_count': len(words), 'clips': len(plan.clips), 'audio_items': len(plan.audio)})
        if words:
            srt(words, plan.subtitles, output.with_suffix('.srt'))
        check_job(jid)
        relative = str(output.relative_to(DATA))
        db.execute('UPDATE montage_projects SET render_path=?,render_revision=? WHERE id=?',
                   (relative, payload['revision'], payload['project_id']))
        checkpoints = json.loads(db.one('SELECT checkpoints FROM jobs WHERE id=?', (jid,))['checkpoints'])
        db.job_update(jid, checkpoints=db.dump({**checkpoints, 'output_path': relative, 'qc': qc}))
        db.log(jid, 'QC passed: full decode, geometry, duration, FPS, audio timeline')
    except BaseException:
        output.unlink(missing_ok=True)
        output.with_suffix('.srt').unlink(missing_ok=True)
        raise
    finally:
        shutil.rmtree(folder, ignore_errors=True)

