def music_limits():
    from .audio_replacement import music_stats
    settings = db.settings()
    stats = music_stats()
    queued = [json.loads(j['payload']) for j in db.rows("SELECT payload FROM jobs WHERE kind='montage_music' AND status IN ('Queued','Running','Paused')")]
    return {'requests_left': max(0, settings['music_request_limit'] - stats['requests'] - len(queued)),
            'seconds_left': max(0, settings['music_seconds_limit'] - stats['seconds'] - sum(q.get('duration', 0) for q in queued)),
            'model': settings['music_model']}

def music_preflight(duration):
    from .config import secret
    if not secret('elevenlabs'):
        raise ValueError('Добавьте ключ ElevenLabs в Настройки → Озвучка')
    if duration < 3:
        raise ValueError('Монтаж короче 3 секунд: Eleven Music создаёт дорожки от 3 секунд')
    limits = music_limits()
    if limits['requests_left'] < 1:
        raise ValueError('Исчерпан лимит запросов Eleven Music. Увеличьте его в Настройки → Озвучка → Eleven Music.')
    if limits['seconds_left'] < duration:
        raise ValueError(f'Нужно {math.ceil(duration)} с музыки, осталось {math.floor(limits["seconds_left"])} с лимита. '
                         'Увеличьте лимит в Настройки → Озвучка → Eleven Music.')

def generate_project_music(job):
    """Paid Eleven Music request → audio file in the montage library → background track in the project."""
    from .audio_replacement import compose_music
    jid = job['id']
    payload = json.loads(job['payload'])
    settings = db.settings()
    duration = payload['duration']
    request = {'prompt': payload['prompt'], 'music_length_ms': max(3000, math.ceil(duration * 1000)),
               'model_id': settings['music_model'], 'force_instrumental': True}
    # The nonce makes every click a new variation, while a retried job reuses its own paid result.
    digest = hashlib.sha256(db.dump(['montage-music-v1', payload['nonce'], request]).encode()).hexdigest()
    db.job_update(jid, stage='ElevenLabs сочиняет музыку', progress=15)
    path, record = compose_music(request, digest, settings, duration, jid)
    check_job(jid)
    db.job_update(jid, stage='Добавляю дорожку в монтаж', progress=90)
    copy = DATA / 'temp' / f'{jid}-music.mp3'
    shutil.copy2(path, copy)
    try:
        media = register_media(copy, f'AI-музыка · {payload["label"]}.mp3')
    finally:
        copy.unlink(missing_ok=True)
    item = {'id': 'ai' + jid[:12], 'kind': 'music', 'label': payload['label'], 'media_id': media['id'],
            'at': 0, 'offset': 0, 'volume': .35, 'fade_in': 0}
    with db.WRITE_LOCK:
        row = db.one('SELECT * FROM montage_projects WHERE id=?', (payload['project_id'],))
        if row:
            plan = MontagePlan.model_validate_json(row['data'])
            length = min(media['duration'], max(plan.duration(), .5))
            track = AudioItem(**item, duration=round(length, 3), fade_out=round(min(2, length / 4), 2))
            # One AI background at a time: a new variation replaces the previous one (older ones stay in «Варианты»).
            plan.audio = [a for a in plan.audio if a.kind != 'music'] + [track]
            db.execute('UPDATE montage_projects SET data=?,revision=revision+1,updated_at=? WHERE id=?',
                       (plan.model_dump_json(), time.time(), row['id']))
    checkpoints = json.loads(db.one('SELECT checkpoints FROM jobs WHERE id=?', (jid,))['checkpoints'])
    db.job_update(jid, checkpoints=db.dump({**checkpoints, 'media_id': media['id'], 'label': payload['label'],
                                           'duration': media['duration'], 'song_id': record.get('song_id')}))
    db.log(jid, f'Eleven Music {record.get("model")}: {media["duration"]:.1f}s added to montage')

def music_variants(pid):
    result = []
    for job in db.rows("SELECT id,checkpoints,created_at FROM jobs WHERE kind='montage_music' AND status='Completed' AND payload LIKE ? "
                       'ORDER BY created_at DESC LIMIT 12', (f'%"project_id": "{pid}"%',)):
        data = json.loads(job['checkpoints'])
        row = db.one('SELECT * FROM montage_media WHERE id=?', (data.get('media_id'),))
        if row:
            result.append({**media_json(row), 'label': data.get('label', ''), 'created_at': job['created_at'], 'job_id': job['id']})
    return result

def active_job(pid, kind):
    for job in db.rows("SELECT id,payload,status,stage,progress FROM jobs WHERE kind=? AND status IN ('Queued','Running','Paused')", (kind,)):
        if json.loads(job['payload']).get('project_id') == pid:
            return job
    return None

def enqueue(kind, pid, title, payload):
    with db.WRITE_LOCK:
        existing = active_job(pid, kind)
        if existing:
            return existing['id']
        jid, now = db.uid(), time.time()
        db.execute('INSERT INTO jobs(id,source_id,clip_id,kind,status,payload,created_at,updated_at) VALUES(?,?,?,?,?,?,?,?)',
                   (jid, None, None, kind, 'Queued', db.dump({**payload, 'project_id': pid, 'title': title}), now, now))
        return jid

