@router.post('/media')
async def upload_media(files: list[UploadFile] = File(...), confirmed: bool = Form(False)):
    if not confirmed:
        raise ValueError('Подтвердите, что у вас есть права на загружаемые файлы')
    if len(files) > 40:
        raise ValueError('Не больше 40 файлов за раз')
    limit = db.settings()['max_upload_mb'] * 1024 ** 2
    result = []
    for uploaded in files:
        suffix = Path(uploaded.filename or '').suffix.lower()
        temp = DATA / 'temp' / f'{db.uid()}{suffix}'
        try:
            if suffix not in VIDEO_EXT and suffix not in AUDIO_EXT:
                raise ValueError('Неподдерживаемый формат файла')
            size = 0
            with temp.open('wb') as out:
                while chunk := await uploaded.read(1024 ** 2):
                    size += len(chunk)
                    if size > limit:
                        raise ValueError('Файл превышает лимит загрузки')
                    check_space(len(chunk), db.settings()['min_free_mb'])
                    out.write(chunk)
            result.append(await asyncio.to_thread(register_media, temp, uploaded.filename or f'file{suffix}'))
        except (ValueError, RuntimeError, OSError) as error:
            result.append({'name': uploaded.filename, 'error': redact(str(error))})
        finally:
            temp.unlink(missing_ok=True)
            await uploaded.close()
    return result

