def project_json(row, detail=False):
    plan = MontagePlan.model_validate_json(row['data'])
    result = {'id': row['id'], 'title': row['title'], 'revision': row['revision'], 'updated_at': row['updated_at'],
              'created_at': row['created_at'], 'duration': plan.duration(), 'clip_count': len(plan.clips),
              'format': plan.format, 'video_url': f'/api/montage/projects/{row["id"]}/video' if row['render_path'] else None,
              'stale': bool(row['render_path'] and row['render_revision'] != row['revision'])}
    first = plan.clips[0] if plan.clips else None
    try:
        result['thumbnail_url'] = resolve(first.media_kind, first.media_id)['thumbnail_url'] if first else None
    except ValueError:
        result['thumbnail_url'] = None
    if detail:
        result['plan'] = plan.model_dump()
        media = {}
        for clip in plan.clips:
            try:
                info = resolve(clip.media_kind, clip.media_id)
                media[clip.id] = {k: info[k] for k in ('title', 'duration', 'width', 'height', 'has_audio', 'media_url', 'thumbnail_url')}
            except ValueError as error:
                media[clip.id] = {'error': str(error)}
        for item in plan.audio:
            audio = db.one('SELECT * FROM montage_media WHERE id=?', (item.media_id,))
            media[item.id] = {**media_json(audio), 'title': audio['name']} if audio else {'error': 'Аудиофайл не найден'}
        result['media'] = media
        model = whisper_model()
        words = {}
        for clip in plan.clips:
            try:
                words[clip.id] = clip_words(plan, clip, model)
            except ValueError:
                words[clip.id] = None
        result['words'] = words
        result['jobs'] = {kind: active_job(row['id'], kind) for kind in ('montage', 'montage_words', 'montage_music')}
        result['music_variants'] = music_variants(row['id'])
        last = db.one("SELECT id,status,error,checkpoints FROM jobs WHERE kind='montage' AND payload LIKE ? ORDER BY created_at DESC LIMIT 1",
                      (f'%"project_id": "{row["id"]}"%',))
        result['last_render'] = {'id': last['id'], 'status': last['status'], 'error': last['error'],
                                 'qc': json.loads(last['checkpoints']).get('qc')} if last else None
    return result

